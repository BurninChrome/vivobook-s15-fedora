#!/bin/bash
# SPDX-License-Identifier: MIT
#
# Build the kernel-vivobook source RPM: Fedora's kernel SRPM (see BASE) plus
# kernel/patches/series as linux-kernel-test.patch, kernel/config/kernel-local,
# and "%define buildid .vivobookN". Nothing else in Fedora's spec is changed.
#
# Usage: packaging/kernel/prepare-srpm.sh [--srpm FEDORA.src.rpm] [--out DIR]
#                                         [--check-tree LINUX_GIT_TREE]
#   --srpm        use a downloaded Fedora SRPM (default: download FEDORA_NVR from Koji)
#   --out         output directory (default: packaging/kernel/out)
#   --check-tree  also check that the series applies to this tree (git apply --check);
#                 the tree must be Fedora's prepared source (rpmbuild -bp) at HEAD
# No root needed. Requires rpm-build, and curl to download.
# Afterwards: copr-cli build BurninChrome/vivobook-s15 OUT/kernel-*.src.rpm
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
# shellcheck source=/dev/null
. "$HERE/BASE"
SRPM=""
OUT="$HERE/out"
TREE=""
while [ $# -gt 0 ]; do
	case $1 in
		--srpm) SRPM=$2; shift 2 ;;
		--out) OUT=$2; shift 2 ;;
		--check-tree) TREE=$2; shift 2 ;;
		*) echo "unknown option: $1" >&2; exit 2 ;;
	esac
done
BUILDID=.vivobook$VIVOBOOK_RELEASE

W=$(mktemp -d)
trap 'rm -rf "$W"' EXIT
mkdir -p "$OUT"

if [ -z "$SRPM" ]; then
	# kernel-7.3.0-0.rc6...fc46 -> packages/kernel/7.3.0/0.rc6...fc46/src/
	v=${FEDORA_NVR#kernel-}; ver=${v%%-*}; rel=${v#*-}
	SRPM="$OUT/$FEDORA_NVR.src.rpm"
	if [ ! -f "$SRPM" ]; then
		curl -fL --retry 3 -o "$SRPM.part" \
			"https://kojipkgs.fedoraproject.org/packages/kernel/$ver/$rel/src/$FEDORA_NVR.src.rpm"
		mv "$SRPM.part" "$SRPM"
	fi
fi
case "$(basename "$SRPM")" in
	"$FEDORA_NVR.src.rpm") ;;
	*) echo "warning: $SRPM is not $FEDORA_NVR (packaging/kernel/BASE)" >&2 ;;
esac
rpm -K --nosignature "$SRPM" >/dev/null || { echo "digest check failed: $SRPM" >&2; exit 1; }

rpm --define "_topdir $W" -i "$SRPM" 2>/dev/null
SPEC=$W/SPECS/kernel.spec
[ -f "$SPEC" ] || { echo "no kernel.spec in $SRPM" >&2; exit 1; }
grep -q 'linux-kernel-test.patch' "$SPEC" || { echo "spec has no linux-kernel-test.patch hook" >&2; exit 1; }
grep -q 'kernel-local' "$SPEC" || { echo "spec has no kernel-local hook" >&2; exit 1; }

mapfile -t patches < <(grep -v -E '^[[:space:]]*(#|$)' "$ROOT/kernel/patches/series")
{
	echo "ASUS Vivobook S 15 (vivobook-s15-fedora): local patch set ($BUILDID),"
	echo "generated by packaging/kernel/prepare-srpm.sh. Do not edit."
	echo "Patches:"
	for p in "${patches[@]}"; do echo "  $p"; done
	echo
	for p in "${patches[@]}"; do cat "$ROOT/kernel/patches/$p"; echo; done
} > "$W/SOURCES/linux-kernel-test.patch"

if [ -n "$TREE" ]; then
	git -C "$TREE" apply --check < "$W/SOURCES/linux-kernel-test.patch"
	echo "series applies to $TREE"
fi

cp "$ROOT/kernel/config/kernel-local" "$W/SOURCES/kernel-local"
# Fedora ships "# define buildid .local"; set it either way.
sed -i -E "s/^(# ?)?%?define buildid .*/%define buildid $BUILDID/" "$SPEC"
grep -q "^%define buildid $BUILDID" "$SPEC" || { echo "could not set buildid" >&2; exit 1; }

rpmbuild --define "_topdir $W" -bs "$SPEC" >/dev/null
mv "$W"/SRPMS/*.src.rpm "$OUT/"
ls -1 "$OUT"/*"${BUILDID}"*.src.rpm
